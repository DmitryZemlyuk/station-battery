// Generates ui/icons.js from the official icon packages:
//   npm i @fluentui/svg-icons ionicons && node tools/gen-icons.mjs <node_modules dir>
// Windows uses Fluent UI System Icons (Microsoft, MIT). macOS uses Ionicons (MIT),
// whose outline style is the closest freely licensed match to SF Symbols.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const nm = process.argv[2] || "node_modules";
const fluent = (name) => {
  const svg = readFileSync(join(nm, "@fluentui/svg-icons/icons", `${name}.svg`), "utf8");
  const vb = svg.match(/viewBox="([^"]+)"/)[1];
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  return `<svg viewBox="${vb}" fill="currentColor" aria-hidden="true">${inner}</svg>`;
};
const ion = (name) => {
  let svg = readFileSync(join(nm, "ionicons/dist/svg", `${name}.svg`), "utf8");
  const vb = svg.match(/viewBox="([^"]+)"/)[1];
  let inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title>.*?<\/title>/, "");
  // Ionicons style through classes / inline style; make it self-contained.
  inner = inner
    .replace(/class="ionicon-fill-none ionicon-stroke-width"/g, 'fill="none" stroke="currentColor" stroke-width="30"')
    .replace(/class="ionicon-stroke-width"/g, 'stroke="currentColor" stroke-width="30"')
    .replace(/class="ionicon-fill-none"/g, 'fill="none" stroke="currentColor"')
    .replace(/style="[^"]*"/g, "")
    .replace(/stroke-width="32"/g, 'stroke-width="30"')
    .replace(/stroke="#000"/g, 'stroke="currentColor"');
  return `<svg viewBox="${vb}" fill="currentColor" aria-hidden="true">${inner}</svg>`;
};

const icons = {
  win: {
    station: fluent("battery_7_20_regular"),
    language: fluent("local_language_20_regular"),
    autostart: fluent("power_20_regular"),
    tray: fluent("panel_bottom_20_regular"),
    ble: fluent("bluetooth_20_regular"),
    cloud: fluent("cloud_20_regular"),
    notifyLow: fluent("battery_warning_20_regular"),
    notifyFull: fluent("battery_checkmark_20_regular"),
    gear: fluent("settings_20_regular"),
    in: fluent("arrow_down_16_regular"),
    out: fluent("arrow_up_16_regular"),
    bolt: fluent("flash_20_filled"),
  },
  mac: {
    tabGeneral: ion("settings-outline"),
    tabSources: ion("radio-outline"),
    tabNotifications: ion("notifications-outline"),
    bolt: ion("flash"),
  },
};

const out = `// Generated by tools/gen-icons.mjs. Do not edit by hand.
// Windows: Fluent UI System Icons (c) Microsoft, MIT. macOS: Ionicons (c) Ionic, MIT.
window.SB_ICONS = ${JSON.stringify(icons, null, 2)};
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), "../ui/icons.js");
writeFileSync(dest, out);
console.log("wrote", dest, out.length, "bytes");
